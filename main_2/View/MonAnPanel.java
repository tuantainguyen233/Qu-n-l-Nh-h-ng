    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
   int row = tblMonAn.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn món cần sửa!");
        return;
    }

    try {
        int maMon = Integer.parseInt(
            tblMonAn.getValueAt(row, 0).toString()
        );

        String tenMon = txtTenMon.getText().trim();
        BigDecimal donGia = new BigDecimal(txtDonGia.getText().trim());

        LoaiMon loai = (LoaiMon) cboMaLoai.getSelectedItem();
        String trangThai = tblMonAn.getValueAt(row, 4).toString();

        if (tenMon.isEmpty() || loai == null
                || donGia.compareTo(BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin!");
            return;
        }

        MonAn mon = null;

        List<MonAn> list = monAnDao.getAll();

        for (MonAn m : list) {
            if (m.getMaMon() == maMon) {
                mon = m;
                break;
            }
        }

        if (mon == null) {
            JOptionPane.showMessageDialog(this, "Không tìm thấy món ăn!");
            return;
        }

        mon.setTenMon(tenMon);
        mon.setMaLoai(loai.getMaLoai());
        mon.setDonGia(donGia);
        mon.setTrangThai(trangThai);

        if (monAnDao.update(mon)) {
            JOptionPane.showMessageDialog(this, "Sửa món ăn thành công!");
            loadDataToTable();
        } else {
            JOptionPane.showMessageDialog(this, "Sửa món ăn thất bại!");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Đơn giá phải là số!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
         int row = tblMonAn.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn món cần xóa!");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Bạn có chắc muốn xóa món ăn này không?",
        "Xác nhận xóa",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        String maMon = tblMonAn.getValueAt(row, 0).toString();

        if (monAnDao.delete(maMon)) {
            JOptionPane.showMessageDialog(this, "Xóa món ăn thành công!");
            loadDataToTable();
        } else {
            JOptionPane.showMessageDialog(this, "Xóa món ăn thất bại!");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
    }
    }//GEN-LAST:event_btnXoaActionPerformed

    private void tblMonAnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMonAnMouseClicked
       int row = tblMonAn.getSelectedRow();

if (row >= 0) {
    txtMaMon.setText(tblMonAn.getValueAt(row, 0).toString());
    txtTenMon.setText(tblMonAn.getValueAt(row, 1).toString());
    txtDonGia.setText(tblMonAn.getValueAt(row, 3).toString());

    String tenLoai = tblMonAn.getValueAt(row, 2).toString();

    for (int i = 0; i < cboMaLoai.getItemCount(); i++) {
        LoaiMon loai = cboMaLoai.getItemAt(i);

        if (loai.getTenLoai().equals(tenLoai)) {
            cboMaLoai.setSelectedItem(loai);
            break;
        }
    }
}
    }//GEN-LAST:event_tblMonAnMouseClicked

    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
         String keyword = txtTimKiem.getText().trim();

        List<MonAn> list = monAnDao.search(keyword);

        tableModel.setRowCount(0);

        for (MonAn mon : list) {
            String tenLoai = "";

            for (LoaiMon loai : loaiMonDao.getAll()) {
                if (loai.getMaLoai() == mon.getMaLoai()) {
                    tenLoai = loai.getTenLoai();
                    break;
                }
            }

            tableModel.addRow(new Object[]{
                mon.getMaMon(),
                mon.getTenMon(),
                tenLoai,
                mon.getDonGia(),
                mon.getTrangThai()
            });
        }
    }//GEN-LAST:event_btnTimKiemActionPerformed


