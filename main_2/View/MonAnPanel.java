    private void initTable() {
        String[] columns = {
        "Mã Món",
        "Tên Món",
        "Loại",
        "Đơn Giá",
        "Trạng Thái"
    };

    tableModel = new DefaultTableModel(columns, 0);
    tblMonAn.setModel(tableModel);
    }

    private void loadDataToTable() {
        tableModel.setRowCount(0);

    List<MonAn> list = monAnDao.getAll();

    for (MonAn mon : list) {
        LoaiMon loai = loaiMonDao.getAll()
                .stream()
                .filter(lm -> lm.getMaLoai() == mon.getMaLoai())
                .findFirst()
                .orElse(null);

        String tenLoai = "";
        if (loai != null) {
            tenLoai = loai.getTenLoai();
        }

        Object[] row = {
            mon.getMaMon(),  // lấy lần lượt dữ liệu của đối tượng mon
            mon.getTenMon(),
            tenLoai,
            mon.getDonGia(),
            mon.getTrangThai()
        };

        tableModel.addRow(row); // đoạn này thêm từng dòng dlieu lên nè
    }
    }

    private void loadDataToCombobox() {
       cboMaLoai.removeAllItems();

    List<LoaiMon> list = loaiMonDao.getAll();

    for (LoaiMon loai : list) {
        cboMaLoai.addItem(loai);  // các đối tượng được đưa vào combobox và hiển thị tên nhờ tostring
    }
    }

