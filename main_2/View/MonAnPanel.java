    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
     
try {
    int maMon = Integer.parseInt(txtMaMon.getText().trim());
    String tenMon = txtTenMon.getText().trim();
    BigDecimal donGia = new BigDecimal(txtDonGia.getText().trim());

    LoaiMon loai = (LoaiMon) cboMaLoai.getSelectedItem();
    String trangThai = "Còn món";

    if (tenMon.isEmpty() || loai == null || donGia.compareTo(BigDecimal.ZERO) < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin!");
        return;
    }

    MonAn mon = new MonAn(
        maMon,
        tenMon,
        loai.getMaLoai(),
        donGia,
        trangThai
    );

    if (monAnDao.insert(mon)) {
        JOptionPane.showMessageDialog(this, "Thêm món ăn thành công!");
        loadDataToTable();
    } else {
        JOptionPane.showMessageDialog(this, "Thêm món ăn thất bại!");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Mã món và đơn giá phải là số!");
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
}

    }//GEN-LAST:event_btnThemActionPerformed

